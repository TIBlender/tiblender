"""Shared helpers that read the committed expected run.

`sample_runs/offline_three_cycles/expected/summary.json` is regenerated by
`tiblender write-expected` and verified by `tiblender verify-sample`. These
helpers expose its counters to the tests.
Not a `test_*.py` module: it holds no tests of its own.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXPECTED_SUMMARY = ROOT / "sample_runs" / "offline_three_cycles" / "expected" / "summary.json"

# `cycles_run=3`, `cycle_002_posts=34`, `cycle_003_dynamic_queries=0`, ...
_COUNTER_RE = re.compile(r"\b(cycles_run|cycle_\d{3}_(?:posts|reports|dynamic_queries))=(\d+)\b")
# The standalone `reports=<n>` line printed by `build-viewer`.
_VIEWER_REPORTS_RE = re.compile(r"^reports=(\d+)$", re.MULTILINE)
# "..., 5 reports generated, ..." in the resource notes.
_REPORTS_PHRASE_RE = re.compile(r"\b(\d+) reports\b")

_NUMBER_WORDS = {
    0: "zero",
    1: "once",
    2: "twice",
    3: "three times",
    4: "four times",
    5: "five times",
}


def load_expected_summary() -> dict:
    assert EXPECTED_SUMMARY.is_file(), (
        f"missing {EXPECTED_SUMMARY}; regenerate it with `tiblender write-expected`"
    )
    return json.loads(EXPECTED_SUMMARY.read_text(encoding="utf-8"))


def expected_console_counters() -> dict[str, int]:
    """Every `name=value` counter a `run-cycles` console transcript may quote."""
    cycles = load_expected_summary()["cycles"]
    counters: dict[str, int] = {"cycles_run": len(cycles)}
    for label, cycle in cycles.items():
        counters[f"{label}_posts"] = int(cycle["posts_loaded"])
        counters[f"{label}_reports"] = int(cycle["reports"])
        counters[f"{label}_dynamic_queries"] = len(cycle["dynamic_queries"])
    return counters


def expected_total_reports() -> int:
    return sum(int(cycle["reports"]) for cycle in load_expected_summary()["cycles"].values())


def expected_trend_counts() -> dict[str, dict[str, int]]:
    return {
        label: {axis: int(count) for axis, count in cycle["trend_counts"].items()}
        for label, cycle in load_expected_summary()["cycles"].items()
    }


def firing_trend_axes() -> list[tuple[str, str, int]]:
    """`(cycle label, axis, count)` for every axis that actually fires."""
    return sorted(
        (label, axis, count)
        for label, counts in expected_trend_counts().items()
        for axis, count in counts.items()
        if count
    )


def number_word(count: int) -> str:
    assert count in _NUMBER_WORDS, f"no prose spelling recorded for {count}; extend _NUMBER_WORDS"
    return _NUMBER_WORDS[count]


def quoted_console_counters(text: str) -> dict[str, int]:
    return {name: int(value) for name, value in _COUNTER_RE.findall(text)}


def quoted_viewer_report_counts(text: str) -> list[int]:
    return [int(value) for value in _VIEWER_REPORTS_RE.findall(text)]


def quoted_reports_phrases(text: str) -> list[int]:
    return [int(value) for value in _REPORTS_PHRASE_RE.findall(text)]


# The bundle must replay at least this share of each tool's external calls in
# the committed offline run. Below it, the package's "recorded tool responses
# stand in for the live external services" claim stops being true for that
# tool -- which is exactly how GITHUB_SEARCH shipped at 0 % while the README
# said otherwise. Not 100 %: a handful of requests are pivoted from evidence
# that only appears once the *newly* recorded responses are in place, and
# chasing the last few would loop indefinitely.
MIN_TOOL_REPLAY_RATE = 0.95


def expected_replay_rates() -> dict[str, dict[str, float]]:
    """Per-tool recorded-response replay totals across the committed run."""
    totals: dict[str, dict[str, float]] = {}
    for cycle in load_expected_summary()["cycles"].values():
        for tool_type, row in (cycle.get("tool_recording_replay", {}).get("by_tool") or {}).items():
            bucket = totals.setdefault(tool_type, {"calls": 0, "hits": 0, "misses": 0})
            for field in ("calls", "hits", "misses"):
                bucket[field] += int(row[field])
    for bucket in totals.values():
        bucket["hit_rate"] = round(bucket["hits"] / bucket["calls"], 4) if bucket["calls"] else 0.0
    return {tool_type: totals[tool_type] for tool_type in sorted(totals)}


def expected_overall_replay_rate() -> float:
    totals = expected_replay_rates()
    calls = sum(int(row["calls"]) for row in totals.values())
    hits = sum(int(row["hits"]) for row in totals.values())
    return round(hits / calls, 4) if calls else 0.0


def quoted_replay_percentages(text: str) -> dict[str, float]:
    """`| WHOIS_LOOKUP | 40 | 40 | 100.0 % |` rows quoted in prose."""
    pattern = re.compile(r"^\|\s*`?([A-Z_]+)`?\s*\|[^|]*\|[^|]*\|\s*([0-9]+(?:\.[0-9]+)?)\s*%\s*\|", re.MULTILINE)
    return {name: float(value) for name, value in pattern.findall(text)}
